import ts from "typescript";
import type { ExampleEntry, ExampleMeta } from "../src/contract.js";

/** One file the generator writes, relative to `examples/`. */
export interface GenFile {
  readonly path: string;
  readonly text: string;
}

const parse = (source: string, fileName: string): ts.SourceFile =>
  ts.createSourceFile(
    fileName,
    source,
    ts.ScriptTarget.Latest,
    true,
    fileName.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
const exported = (s: ts.Statement): boolean =>
  ts.canHaveModifiers(s) && (ts.getModifiers(s) ?? []).some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
const isMeta = (s: ts.Statement): s is ts.VariableStatement =>
  ts.isVariableStatement(s) &&
  exported(s) &&
  s.declarationList.declarations.some((d) => ts.isIdentifier(d.name) && d.name.text === "meta");
const isContractImport = (s: ts.Statement): boolean =>
  ts.isImportDeclaration(s) &&
  ts.isStringLiteral(s.moduleSpecifier) &&
  s.moduleSpecifier.text.endsWith("/contract.js");

/** `export const meta = { title: "…", tags: ["…"] } satisfies ExampleMeta;`, read from the AST: nothing is executed. */
export function metaOf(source: string, fileName: string): ExampleMeta {
  const st = parse(source, fileName).statements.find(isMeta);
  let init = st?.declarationList.declarations[0]?.initializer;
  while (
    init &&
    (ts.isSatisfiesExpression(init) || ts.isAsExpression(init) || ts.isParenthesizedExpression(init))
  )
    init = init.expression;
  if (!init || !ts.isObjectLiteralExpression(init))
    throw new Error(`${fileName}: needs \`export const meta = { title, tags } satisfies ExampleMeta\``);
  let title: string | undefined;
  let tags: string[] | undefined;
  for (const p of init.properties) {
    if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name)) continue;
    if (p.name.text === "title" && ts.isStringLiteralLike(p.initializer)) title = p.initializer.text;
    if (p.name.text === "tags" && ts.isArrayLiteralExpression(p.initializer))
      tags = p.initializer.elements.map((e) => {
        if (!ts.isStringLiteralLike(e)) throw new Error(`${fileName}: meta.tags must be string literals`);
        return e.text;
      });
  }
  if (title === undefined || tags === undefined)
    throw new Error(`${fileName}: meta needs a literal string \`title\` and a literal string[] \`tags\``);
  return { title, tags };
}

/**
 * The code a reader sees: the module minus `meta`, minus the contract import, with `export default X;` shown as
 * `X;`. Cuts are AST positions on the original text, so comments and formatting survive.
 */
export function codeOf(source: string, fileName: string): string {
  const sf = parse(source, fileName);
  const cuts: [number, number][] = [];
  let hasDefault = false;
  for (const s of sf.statements) {
    if (isMeta(s) || isContractImport(s)) cuts.push([s.getStart(sf), s.getEnd()]);
    else if (ts.isExportAssignment(s) && !s.isExportEquals) {
      cuts.push([s.getStart(sf), s.expression.getStart(sf)]);
      hasDefault = true;
    }
  }
  if (!hasDefault) throw new Error(`${fileName}: an example's default export is its output; there is none`);
  let out = source;
  for (const [a, b] of cuts.sort((x, y) => y[0] - x[0])) out = out.slice(0, a) + out.slice(b);
  out = out.replace(/^\/\/ generated by examples\/scripts\/gen\.ts.*\n/, "");
  return `${out.replace(/\n{3,}/g, "\n\n").trim()}\n`;
}

/** One fenced block under an `@example` tag. */
export interface DocExample {
  readonly symbol: string;
  readonly lang: "ts" | "tsx";
  readonly code: string;
}
const COMMENT = /\/\*\*(?:[^*]|\*(?!\/))*\*\//g;
// A doc comment that cannot contain "*/", then the exported declaration it documents.
const DOC =
  /\/\*\*((?:[^*]|\*(?!\/))*)\*\/\s*export\s+(?:declare\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?|const|let|(?:abstract\s+)?class|interface|type|enum|namespace)\s+([A-Za-z_$][\w$]*)/g;

/**
 * Every fenced block under an `@example` tag of an exported declaration, in source order.
 *
 * The authoring contract (each rule below throws, naming the file):
 * - An `@example` is a fenced ```ts or ```tsx block under the tag (`@example Caption` on the tag line is fine).
 * - Imports come first; the block ends with the expression it shows, which becomes the example's default export
 *   (a trailing declaration or statement is refused).
 * - One block per example; several on one symbol get ids `<symbol>`, `<symbol>-2`, ... (see gen.ts).
 * - Only a doc comment placed directly on a top-level `export [declare|default|async|abstract] function|const|let|
 *   class|interface|type|enum|namespace` is read. An `@example` on a class member, an overload, an `export { x }`
 *   or any other shape throws, so an example can never vanish silently. A column-0 comment on a NON-exported
 *   declaration is ignored.
 * - Hand-written example modules (not docstrings) need `export const meta = { title, tags }` with literal
 *   strings, a default export for the output and imports first; see `metaOf`.
 */
export function extractDocExamples(source: string, fileName: string): DocExample[] {
  const found: DocExample[] = [];
  const read = new Set<number>();
  for (const m of source.matchAll(DOC)) {
    read.add(m.index);
    const symbol = m[2] ?? "";
    const lines = (m[1] ?? "").split("\n").map((l) => l.replace(/^\s*\* ?/, ""));
    for (let i = 0; i < lines.length; i++) {
      if (!/^@example\b/.test(lines[i]?.trim() ?? "")) continue;
      const open = lines.findIndex((l, j) => j > i && /^```/.test(l.trim()));
      const fence = open < 0 ? null : /^```(\w*)\s*$/.exec(lines[open]?.trim() ?? "");
      if (!fence || lines.slice(i + 1, open).some((l) => l.trim().startsWith("@")))
        throw new Error(`${fileName}: @example on ${symbol} must be a fenced \`\`\`ts block`);
      const close = lines.findIndex((l, j) => j > open && l.trim() === "```");
      if (close < 0) throw new Error(`${fileName}: unclosed @example fence on ${symbol}`);
      const lang = fence[1] === "tsx" || fence[1] === "jsx" ? "tsx" : "ts";
      found.push({ symbol, lang, code: `${lines.slice(open + 1, close).join("\n")}\n` });
      i = close;
    }
  }
  for (const c of source.matchAll(COMMENT)) {
    if (read.has(c.index) || !/^\s*\*?\s*@example(?![\w-])/m.test(c[0])) continue;
    const after = source.slice(c.index + c[0].length);
    const topLevel = c.index === 0 || source.charAt(c.index - 1) === String.fromCharCode(10);
    if (
      topLevel &&
      /^\s*(?:declare\s+)?(?:async\s+)?(?:function|const|let|var|class|interface|type|enum)(?![\w$])/.test(
        after,
      )
    )
      continue;
    const first = c[0]
      .split(/\r?\n/)
      .map((l) => l.replace(/^\s*(?:\/\*\*|\*) ?/, "").trim())
      .find((l) => l !== "");
    throw new Error(
      `${fileName}: @example in the doc comment "${first ?? ""}" is not on a top-level exported declaration (put it on the export, not on a member, overload or \`export { x }\`)`,
    );
  }
  return found;
}

/** A docstring example as an example module: its imports, `meta`, then the body with the last expression exported. */
export function docModule(o: DocExample & { readonly from: string; readonly contract: string }): string {
  const sf = parse(o.code, `example.${o.lang}`);
  const firstBody = sf.statements.findIndex((s) => !ts.isImportDeclaration(s));
  const body = firstBody < 0 ? [] : sf.statements.slice(firstBody);
  if (body.some((s) => ts.isImportDeclaration(s)))
    throw new Error(`${o.from}: @example on ${o.symbol} must put its imports first`);
  const last = body.at(-1);
  if (last === undefined || !ts.isExpressionStatement(last))
    throw new Error(`${o.from}: @example on ${o.symbol} must end with the expression it shows`);
  const imports = sf.statements.slice(0, firstBody).map((s) => s.getText(sf));
  const start = body[0]?.getStart(sf) ?? 0;
  const at = last.getStart(sf);
  const meta = `{ title: ${JSON.stringify(o.symbol)}, tags: ${JSON.stringify(["docstring", o.symbol])} }`;
  return [
    `// generated by examples/scripts/gen.ts from ${o.from} (@example on ${o.symbol}) - do not edit`,
    ...imports,
    `import type { ExampleMeta } from ${JSON.stringify(o.contract)};`,
    "",
    `export const meta = ${meta} satisfies ExampleMeta;`,
    "",
    `${o.code.slice(start, at)}export default ${o.code.slice(at).trimEnd()}`,
    "",
  ].join("\n");
}

