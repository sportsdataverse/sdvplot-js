/**
 * sporty's leagues per sport, read from `specs/<sport>.ts` (`export const X_LEAGUES = [...] as const`), minus
 * `custom`; and which sports `surface()` dispatches today (a `case "<sport>":` in api.ts). Only dispatched sports
 * can be drawn through the public API, so only they get gallery surfaces; every other sport is reported so an
 * omission is visible in the generator output. When the dispatcher lands, the sport joins automatically.
 */
export function discoverSporty(
  specs: Readonly<Record<string, string>>,
  apiSource: string,
): { readonly all: Record<string, string[]>; readonly dispatched: Record<string, string[]> } {
  const all: Record<string, string[]> = {};
  const dispatched: Record<string, string[]> = {};
  for (const [sport, text] of Object.entries(specs)) {
    const m = /_LEAGUES\s*=\s*\[([^\]]*)\]/.exec(text);
    if (!m) throw new Error(`specs/${sport}.ts: no \`*_LEAGUES = [...]\` list found`);
    const leagues = [...(m[1] ?? "").matchAll(/"([^"]+)"/g)]
      .map((x) => x[1] ?? "")
      .filter((l) => l !== "custom");
    all[sport] = leagues;
    if (new RegExp(`case "${sport}":`).test(apiSource)) dispatched[sport] = leagues;
  }
  return { all, dispatched };
}
const slug = (s: string): string => s.replace(/[^A-Za-z0-9]+/g, "-");
const HEADER = "// generated by examples/scripts/gen.ts (a gallery family) - do not edit";
const CONTRACT = `import type { ExampleMeta } from "../../../contract.js";`;
const q = (v: unknown): string => JSON.stringify(v);

/** The theme family (THEMES) and the surface family (`sports`: the leagues `discoverSporty` finds). */
export function familyModules(sports: Readonly<Record<string, readonly string[]>>): GenFile[] {
  const themes = THEMES.map((name) => ({
    path: `src/generated/sdvtables/themes/${name}.ts`,
    text: `${HEADER}
import { STANDINGS } from "@sportsdataverse/examples/data";
import { defineTable } from "@sportsdataverse/sdvtables";
import { renderHTMLAsync } from "@sportsdataverse/sdvtables/html";
${CONTRACT}

export const meta = { title: ${q(`Theme: ${name}`)}, tags: ["theme", ${q(name)}] } satisfies ExampleMeta;

const spec = defineTable<(typeof STANDINGS)[number]>()
  .columns((c) => [
    c.logo("team", { league: "nfl" }),
    c.int("wins"),
    c.int("losses"),
    c.int("pf", { label: "PF" }),
    c.int("pa", { label: "PA" }),
    c.colorPills("net_epa", { label: "Net EPA/play", digits: 3, domain: [-0.2, 0.2] }),
  ])
  .theme(${q(name)}${THEME_OPTIONS[name] ?? ""})
  .title("AFC, 2024 regular season")
  .build();
export default await renderHTMLAsync(spec, STANDINGS);
`,
  }));
  const surfaces = Object.entries(sports).flatMap(([sport, leagues]) =>
    leagues.map((league) => ({
      path: `src/generated/sporty/surfaces/${sport}-${slug(league)}.ts`,
      text: `${HEADER}
import { surface } from "@sportsdataverse/sporty";
import { toSVG } from "@sportsdataverse/sporty/svg";
${CONTRACT}

export const meta = { title: ${q(`${sport}: ${league}`)}, tags: ["surface", ${q(sport)}, ${q(league)}] } satisfies ExampleMeta;

// arcs "svg" writes each circle as one arc command; precision 2 keeps 0.01 of a unit. Same drawing, ~8x smaller.
export default toSVG(surface(${q(sport)}, ${q(league)}), { width: 640, arcs: "svg", precision: 2 });
`,
    })),
  );
  return [...themes, ...surfaces];
}

/**
 * The registry (metadata for the gate and the pages) and the browser loaders: every example except `node` ones
 * (they import jsdom, fs, resvg) and `network` ones (the browser would download the real 18 MB manifest).
 */
export function registryModules(entries: readonly ExampleEntry[]): { registry: string; loaders: string } {
  const head = "// generated by examples/scripts/gen.ts - do not edit";
  const rows = entries.map(
    (e) =>
      `  { id: ${q(e.id)}, package: ${q(e.package)}, title: ${q(e.title)}, tags: ${q(e.tags)}, lang: ${q(e.lang)}, file: ${q(e.file)}, code: ${q(e.code)} },`,
  );
  const load = entries
    .filter((e) => !e.tags.includes("node") && !e.tags.includes("network"))
    .map((e) => `  ${q(e.id)}: () => import(${q(`./${e.file.slice(4).replace(/\.tsx?$/, ".js")}`)}),`);
  return {
    registry: `${head}\nimport type { ExampleEntry } from "./contract.js";\n\nexport const EXAMPLES: readonly ExampleEntry[] = [\n${rows.join("\n")}\n];\n`,
    loaders: `${head}\n/** Browser loaders: importing one runs that example. node and network examples are left out. */\nexport const LOADERS: Readonly<Record<string, () => Promise<{ default: unknown }>>> = {\n${load.join("\n")}\n};\n`,
  };
}
